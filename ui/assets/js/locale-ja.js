export function ja(value, category) {
  const raw = String(value ?? "");
  return MAPS[category]?.[raw] ?? raw;
}

export function jaTactic(value) {
  return String(value ?? "")
    .split(",")
    .map((part) => ja(part.trim(), "tactic"))
    .filter(Boolean)
    .join("・");
}

export function jaNarrative(value) {
  return NARRATIVE_MAP[String(value ?? "")] ?? String(value ?? "");
}

export function hasJapanese(value) {
  return /[ぁ-んァ-ヶ一-龠]/.test(String(value ?? ""));
}
